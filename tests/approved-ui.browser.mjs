import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? "playwright-core");
const base = process.env.JUGAAD_BASE_URL ?? "http://127.0.0.1:3000";
const output = process.argv[2];
assert.ok(output, "Pass a screenshot output directory");
await mkdir(output,{recursive:true});
const browser=await chromium.launch({executablePath: process.env.CHROME_BINARY});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(() => {
    navigator.mediaDevices.getUserMedia = async () => { throw new DOMException('Denied for the text fallback test', 'NotAllowedError'); };
  });
  await page.goto(base, { waitUntil: "domcontentloaded", timeout: 90000 });
  await page.locator('.hero-art').waitFor();
  await page.evaluate(()=>document.fonts.ready);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),1440);
  const hero = await page.locator('.hero-copy').boundingBox();
  const poster = await page.locator('.hero-art').boundingBox();
  assert.ok(hero && poster && poster.x > hero.x + hero.width - 1, 'Desktop poster must sit beside the headline');
  await page.screenshot({path:output+'/home-desktop.png',fullPage:true});
  const tryLink = page.getByRole('link',{name:'Try Jugaad'}).first();
  await page.waitForFunction(() => [...document.querySelectorAll('a[href="/workspace"]')]
    .some((link) => Object.keys(link).some((key) => key.startsWith('__reactProps'))));
  await tryLink.click();
  await page.waitForURL('**/workspace', {timeout:90000});
  await page.getByRole('alert').filter({hasText:'Microphone access is unavailable'}).waitFor({timeout:90000});
  await page.getByRole('button',{name:/continue with text/i}).click();
  await page.getByLabel('Service city').selectOption('hyderabad');
  await page.getByRole('button',{name:'Confirm city'}).click();
  await page.getByRole('heading',{name:/let’s speak/i}).waitFor({timeout:90000});
  await page.screenshot({path:output+'/onboarding-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'English'}).click();
  await page.getByRole('button',{name:/continue/i}).click();
  await page.getByLabel('Your name',{exact:true}).fill('UI QA');
  await page.getByRole('button',{name:/continue/i}).click();
  await page.getByRole('heading',{name:/good to have you here, UI QA/i}).waitFor();
  const nav=page.getByRole('navigation',{name:'Primary navigation'});
  assert.deepEqual((await nav.getByRole('button').allTextContents()).map((label) => label.trim()), ['Jugaad', 'Orders', 'Profile']);
  await page.screenshot({path:output+'/jugaad-desktop.png',fullPage:true});
  const input=page.getByRole('textbox',{name:'Message Jugaad'});
  async function ask(text){
    await input.fill(text);
    const pending=page.waitForResponse(r=>r.url().endsWith('/api/agent/interpret')&&r.request().postDataJSON()?.text===text,{timeout:50000});
    await page.getByRole('button',{name:'Send message'}).click();
    const response=await pending;
    assert.equal(response.status(),200);
    return response.json();
  }
  const answer=await ask('Why does rain smell earthy?');
  assert.equal(answer.trace.searchAttempted,false);
  const food=await ask('I want something sweet, maybe cake');
  assert.equal(food.sandbox.offers.length,3);
  await page.getByRole('region',{name:'Offer comparison'}).waitFor();
  await page.screenshot({path:output+'/offers-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'New conversation'}).click();
  await page.getByText('Ask a question or tell me what you’d like to compare.',{exact:false}).waitFor();
  await page.getByRole('region',{name:'Offer comparison'}).waitFor({state:'hidden'});
  await ask('I want something sweet, maybe cake');
  await page.getByRole('region',{name:'Offer comparison'}).waitFor();
  await page.getByRole('button',{name:/choose/i}).first().click();
  const modifier=page.getByRole('button',{name:/add extra cheese/i});
  await modifier.waitFor();
  const customized=page.waitForResponse(r=>r.url().endsWith('/api/commerce')&&r.request().postDataJSON()?.input?.action==='customize');
  await modifier.click();
  assert.ok((await (await customized).json()).quote.offer.selectedModifiers.length);
  await page.getByRole('button',{name:'Apply JUGAAD20'}).click();
  await page.getByRole('button',{name:/approve exact total/i}).click();
  await page.waitForURL('**/payment?**');
  await page.screenshot({path:output+'/payment-desktop.png',fullPage:true});
  await page.getByRole('button',{name:/tap to autofill/i}).click();
  const paid=page.waitForResponse(r=>r.url().endsWith('/api/commerce')&&r.request().postDataJSON()?.input?.action==='pay');
  await page.getByRole('button',{name:/authorize simulated payment/i}).click();
  const result=await (await paid).json();
  assert.equal(result.order.payment,'simulated_no_charge');
  await page.getByRole('link',{name:'View order'}).click();
  await page.waitForURL('**/workspace?tab=orders&receipt=**');
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.order-row').first().waitFor();
  await page.screenshot({path:output+'/orders-desktop.png',fullPage:true});
  await page.locator('.order-row').first().click();
  await page.getByRole('dialog').waitFor();
  await page.getByText('No money was charged.',{exact:true}).waitFor();
  await page.keyboard.press('Escape');
  await nav.getByRole('button',{name:'Profile'}).click();
  await page.getByLabel('Preferred name').fill('UI Returning');
  await page.getByLabel('Conversation language').selectOption('hi-en');
  await page.getByLabel('Service city').selectOption('mumbai');
  await page.getByRole('button',{name:/save changes/i}).click();
  await page.getByText('Changes saved.',{exact:true}).waitFor();
  await nav.getByRole('button',{name:'Jugaad'}).click();
  const applied = page.waitForRequest((request) => request.url().endsWith('/api/agent/interpret') && request.postDataJSON()?.text === 'Hello');
  const greeting = await ask('Hello');
  assert.equal((await applied).postDataJSON().location.cityId, 'mumbai');
  assert.equal(greeting.replyLanguage, 'hi-en');
  await nav.getByRole('button',{name:'Profile'}).click();
  await page.reload();
  await page.getByRole('heading',{name:/make it/i}).waitFor();
  assert.equal(await page.getByLabel('Preferred name').inputValue(),'UI Returning');
  assert.equal(await page.getByLabel('Conversation language').inputValue(),'hi-en');
  assert.equal(await page.getByLabel('Service city').inputValue(),'mumbai');
  await page.screenshot({path:output+'/profile-desktop.png',fullPage:true});
  await nav.getByRole('button',{name:'Jugaad'}).click();
  await page.getByRole('heading',{name:/good to have you here, UI Returning/i}).waitFor();
  await page.getByRole('button',{name:'New conversation'}).click();
  await page.getByText('Ask a question or tell me what you’d like to compare.',{exact:false}).waitFor();
  await nav.getByRole('button',{name:'Orders'}).click();
  await page.locator('.order-row').first().waitFor();
  for (const width of [375,768,1024]) {
    await page.setViewportSize({width,height:850});
    for (const name of ['Jugaad','Orders','Profile']) {
      await nav.getByRole('button',{name}).click();
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width,`${width}px ${name}`);
      if(width===375) await page.screenshot({path:output+'/'+name.toLowerCase()+'-mobile.png',fullPage:true});
    }
  }
  await nav.getByRole('button',{name:'Jugaad'}).click();
  const ended = page.waitForResponse(r=>r.url().endsWith('/api/agent/interpret')&&r.request().postDataJSON()?.text==='End this conversation');
  await page.getByRole('button',{name:'End conversation',exact:true}).click();
  assert.equal((await (await ended).json()).voiceControl,'stop');
  assert.deepEqual(errors,[]);
  console.log('Live browser onboarding, three tabs, Gemini, comparison, add-on, explicit approval, simulated payment, receipt, profile save, refresh, and responsive layouts passed.');
}finally{await browser.close();}
